import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=process.env.DOOM_SOURCE ?? '/Users/sambide/GitHub/reference-material/DOOM/linuxdoom-1.10';
const source=readFileSync(root+'/tables.c','utf8');
let output=`// Generated by scripts/generate-angle-tables.mjs from original tables.c.\n// SHA-256: ${createHash('sha256').update(source).digest('hex')}\n`;
for(const [name,size,type] of [['finesine',10240,'Int32Array'],['tantoangle',2049,'Uint32Array']]){
  const body=source.match(new RegExp('\\b'+name+'\\['+size+'\\]\\s*=\\s*\\{([^}]+)\\}'))?.[1];
  if(!body)throw new Error('Missing '+name);
  const values=body.split(',').map(v=>v.trim()).filter(Boolean).map(Number);
  if(values.length!==size || values.some(v=>!Number.isInteger(v)))throw new Error('Invalid '+name);
  output+=`export const ${name}=new ${type}([\n`;
  for(let i=0;i<values.length;i+=16)output+='  '+values.slice(i,i+16).join(',')+',\n';
  output+=']);\n';
}
writeFileSync('src/math/AngleTables.ts',output);
console.log('Generated 10240 sine and 2049 slope-angle values.');
